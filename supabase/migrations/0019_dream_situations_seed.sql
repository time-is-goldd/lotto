-- 확정적 미래 예측 표현을 쓰지 않고 "전통적으로 ~로 해석된다/~로 여겨지기도 한다/~을 상징하는
-- 꿈으로 보기도 한다" 같은 완곡한 표현만 사용한다. 당첨 확률이 올라간다는 암시도 전혀 없다.
